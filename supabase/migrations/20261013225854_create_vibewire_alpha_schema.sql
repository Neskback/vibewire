/*
# VibeWire Alfa: noticias, favoritos y contacto

1. Nuevas tablas
- `news`: catálogo público y publicaciones de usuarios.
  - `id`: identificador numérico generado por la base.
  - `owner_id`: cuenta autenticada propietaria de una publicación de usuario.
  - `title`, `category`, `description`, `content`, `image_url`: contenido editorial.
  - `published_at`: fecha pública de la noticia.
  - `featured`: indica si aparece como noticia destacada.
  - `is_published`: controla si una publicación aparece en el catálogo público.
  - `created_at`, `updated_at`: trazabilidad de la publicación.
- `favorites`: relación privada entre una cuenta y una noticia guardada.
  - `user_id`: cuenta propietaria del favorito.
  - `news_id`: noticia guardada.
- `contact_messages`: mensajes recibidos desde el formulario de contacto.
  - `owner_id`: cuenta autenticada que envía el mensaje, cuando existe.
  - `name`, `email`, `subject`, `message`: datos enviados por el visitante.
  - `status`, `created_at`: estado operativo y fecha de recepción.

2. Catálogo inicial
- Se cargan las seis noticias editoriales de VibeWire con acceso público.
- Las noticias iniciales no pertenecen a ninguna cuenta y no pueden ser modificadas por usuarios normales.

3. Seguridad
- RLS queda habilitado en todas las tablas nuevas.
- Las noticias publicadas se pueden leer sin iniciar sesión.
- Las cuentas autenticadas solo pueden crear, editar y eliminar sus propias noticias.
- Cada cuenta solo puede leer, crear y eliminar sus propios favoritos.
- Los mensajes de contacto se pueden insertar públicamente, pero no se exponen para lectura pública.
- La propiedad se obtiene de `auth.uid()` y no se acepta desde el cliente.
- Se revocan escrituras sobre columnas de propiedad, auditoría y control editorial.

4. Notas importantes
- No se eliminan tablas ni columnas existentes.
- La migración es idempotente en tablas, índices, políticas y datos iniciales.
- La aprobación administrativa queda preparada mediante `is_published`, pero no se activa un panel administrativo en esta fase.
*/

CREATE TABLE IF NOT EXISTS public.news (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
  title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 5 AND 180),
  category text NOT NULL CHECK (category IN ('IA', 'Desarrollo', 'Tecnología', 'Cultura')),
  description text NOT NULL CHECK (char_length(btrim(description)) BETWEEN 10 AND 160),
  content text NOT NULL CHECK (char_length(btrim(content)) >= 30),
  image_url text NOT NULL CHECK (image_url ~* '^https?://'),
  published_at date NOT NULL DEFAULT current_date,
  featured boolean NOT NULL DEFAULT false,
  is_published boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.favorites (
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  news_id bigint NOT NULL REFERENCES public.news(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, news_id)
);

CREATE TABLE IF NOT EXISTS public.contact_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE SET NULL,
  name text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 3 AND 120),
  email text NOT NULL CHECK (email ~* '^[^[:space:]@]+@[^[:space:]@]+\\.[^[:space:]@]{2,}$'),
  subject text NOT NULL CHECK (subject IN ('Proponer una historia', 'Corrección', 'Otro')),
  message text NOT NULL CHECK (char_length(btrim(message)) BETWEEN 10 AND 5000),
  status text NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'read', 'archived')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS news_public_date_idx ON public.news (published_at DESC) WHERE is_published = true;
CREATE INDEX IF NOT EXISTS news_owner_date_idx ON public.news (owner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS favorites_news_idx ON public.favorites (news_id);
CREATE INDEX IF NOT EXISTS contact_messages_owner_idx ON public.contact_messages (owner_id, created_at DESC);

ALTER TABLE public.news ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.favorites ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contact_messages ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can read published news" ON public.news;
CREATE POLICY "Public can read published news" ON public.news FOR SELECT TO anon, authenticated USING (is_published = true OR owner_id = auth.uid());
DROP POLICY IF EXISTS "Users can create own news" ON public.news;
CREATE POLICY "Users can create own news" ON public.news FOR INSERT TO authenticated WITH CHECK (owner_id = auth.uid());
DROP POLICY IF EXISTS "Users can update own news" ON public.news;
CREATE POLICY "Users can update own news" ON public.news FOR UPDATE TO authenticated USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());
DROP POLICY IF EXISTS "Users can delete own news" ON public.news;
CREATE POLICY "Users can delete own news" ON public.news FOR DELETE TO authenticated USING (owner_id = auth.uid());

DROP POLICY IF EXISTS "Users can read own favorites" ON public.favorites;
CREATE POLICY "Users can read own favorites" ON public.favorites FOR SELECT TO authenticated USING (user_id = auth.uid());
DROP POLICY IF EXISTS "Users can create own favorites" ON public.favorites;
CREATE POLICY "Users can create own favorites" ON public.favorites FOR INSERT TO authenticated WITH CHECK (user_id = auth.uid());
DROP POLICY IF EXISTS "Users can update own favorites" ON public.favorites;
CREATE POLICY "Users can update own favorites" ON public.favorites FOR UPDATE TO authenticated USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());
DROP POLICY IF EXISTS "Users can delete own favorites" ON public.favorites;
CREATE POLICY "Users can delete own favorites" ON public.favorites FOR DELETE TO authenticated USING (user_id = auth.uid());

DROP POLICY IF EXISTS "Anyone can send contact messages" ON public.contact_messages;
CREATE POLICY "Anyone can send contact messages" ON public.contact_messages FOR INSERT TO anon, authenticated WITH CHECK (owner_id = auth.uid() OR owner_id IS NULL);
DROP POLICY IF EXISTS "Users can read own contact messages" ON public.contact_messages;
CREATE POLICY "Users can read own contact messages" ON public.contact_messages FOR SELECT TO authenticated USING (owner_id = auth.uid());
DROP POLICY IF EXISTS "Users can update own contact messages" ON public.contact_messages;
CREATE POLICY "Users can update own contact messages" ON public.contact_messages FOR UPDATE TO authenticated USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());
DROP POLICY IF EXISTS "Users can delete own contact messages" ON public.contact_messages;
CREATE POLICY "Users can delete own contact messages" ON public.contact_messages FOR DELETE TO authenticated USING (owner_id = auth.uid());

REVOKE INSERT, UPDATE, DELETE ON public.news FROM anon;
REVOKE INSERT, UPDATE, DELETE ON public.favorites FROM anon;
REVOKE SELECT, UPDATE, DELETE ON public.contact_messages FROM anon;
REVOKE UPDATE ON public.news FROM authenticated;
GRANT UPDATE (title, category, description, content, image_url, featured, is_published) ON public.news TO authenticated;
REVOKE UPDATE ON public.favorites FROM authenticated;
REVOKE UPDATE ON public.contact_messages FROM authenticated;
GRANT UPDATE (status) ON public.contact_messages TO authenticated;

